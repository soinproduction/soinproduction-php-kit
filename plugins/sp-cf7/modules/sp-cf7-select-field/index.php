	add_filter( 'wpcf7_validate_custom_select*', function ( $result, $tag ) {
		$name = is_object( $tag ) ? ( $tag->name ?? '' ) : '';
		if ( ! $name ) {
			return $result;
		}
		$val = isset( $_POST[ $name ] ) ? wp_unslash( $_POST[ $name ] ) : '';
		$is_empty = is_array( $val )
			? empty( array_filter( $val, function ( $value ) { return trim( (string) $value ) !== ''; } ) )
			: trim( (string) $val ) === '';
		if ( $is_empty && method_exists( $result, 'invalidate' ) ) {
			$result->invalidate( $tag, wpcf7_get_message( 'invalid_required' ) );
		}

		return $result;
	}, 10, 2 );

	function cf7cs_extract_required_names( $template ) {
		if ( ! is_string( $template ) || $template === '' ) {
			return [];
		}

		preg_match_all( '/\[custom_select\*\s+([^\s\]"]+)/i', $template, $matches );

		return array_values( array_unique( array_filter( array_map( 'sanitize_key', $matches[1] ?? [] ) ) ) );
	}

	add_filter( 'wpcf7_validate', function ( $result ) {
		$contact_form = class_exists( 'WPCF7_ContactForm' ) ? WPCF7_ContactForm::get_current() : null;
		if ( ! $contact_form || ! method_exists( $contact_form, 'prop' ) ) {
			return $result;
		}

		foreach ( cf7cs_extract_required_names( $contact_form->prop( 'form' ) ) as $name ) {
			$value = isset( $_POST[ $name ] ) ? wp_unslash( $_POST[ $name ] ) : '';
			$is_empty = is_array( $value )
				? empty( array_filter( $value, function ( $item ) { return trim( (string) $item ) !== ''; } ) )
				: trim( (string) $value ) === '';

			if ( $is_empty && method_exists( $result, 'invalidate' ) && class_exists( 'WPCF7_FormTag' ) ) {
				$result->invalidate( new WPCF7_FormTag( [
					'type'     => 'custom_select*',
					'basetype' => 'custom_select',
					'name'     => $name,
				] ), wpcf7_get_message( 'invalid_required' ) );
			}
		}

		return $result;
	}, 20 );

	add_action( 'wpcf7_swv_create_schema', function ( $schema, $contact_form ) {
		if ( ! is_object( $contact_form ) || ! method_exists( $contact_form, 'scan_form_tags' ) || ! function_exists( 'wpcf7_swv_create_rule' ) ) {
			return;
		}

		$tags = $contact_form->scan_form_tags( [
			'type' => [ 'custom_select*' ],
		] );
		$required_names = cf7cs_extract_required_names( $contact_form->prop( 'form' ) );

		foreach ( $tags as $tag ) {
			if ( ! empty( $tag->name ) ) {
				$required_names[] = sanitize_key( $tag->name );
			}
		}

		foreach ( array_unique( array_filter( $required_names ) ) as $name ) {
			$schema->add_rule(
				wpcf7_swv_create_rule( 'required', [
					'field' => $name,
					'error' => wpcf7_get_message( 'invalid_required' ),
				] )
			);
		}
	}, 10, 2 );

	add_filter( 'wpcf7_form_elements', function ( $html ) {
		if ( strpos( $html, '[custom_select' ) === false ) {
			return $html;
		}

		return preg_replace_callback( '/\[(custom_select\*?|custom_select)\s+([^\]]+)\]/', function ( $m ) {
			$raw = trim( $m[2] );
			preg_match_all( '/([^\s"]+)(?:\s+"([^"]*)")?/', $raw, $parts, PREG_SET_ORDER );
			$name = '';
			$is_required = substr( $m[1], -1 ) === '*';
			$a    = [
				'class'       => 'custom-select',
				'type'        => 'single',
				'placeholder' => '',
				'id'          => '',
				'options'     => '',
				'active'      => '',
				'disabled'    => '',
				'required'         => $is_required,
				'control_class'    => 'wpcf7-form-control wpcf7-custom-select' . ( $is_required ? ' wpcf7-validates-as-required' : '' ),
				'validation_error' => '',
				'wpcf7_wrap'       => true,
			];
			foreach ( $parts as $i => $p ) {
				$key = $p[1];
				$val = $p[2] ?? '';
				if ( $i === 0 && strpos( $key, ':' ) === false ) {
					$name = $key;
					continue;
				}
				if ( $val === '' && strpos( $key, ':' ) !== false ) {
					[ $key, $val ] = explode( ':', $key, 2 );
				}
				if ( $key === 'class' ) {
					$a['class'] = trim( $val ) ?: 'custom-select';
				} elseif ( $key === 'type' ) {
					$a['type'] = $val ?: 'single';
				} elseif ( $key === 'placeholder' ) {
					$a['placeholder'] = $val;
				} elseif ( $key === 'id' ) {
					$a['id'] = $val;
				} elseif ( $key === 'options' ) {
					$a['options'] = $val;
				} elseif ( $key === 'active' ) {
					$a['active'] = $val;
				} elseif ( $key === 'disabled' ) {
					$a['disabled'] = $val;
				}
			}
			if ( ! $name ) {
				return '';
			}
			$a['name'] = $name;
			if ( function_exists( 'wpcf7_get_validation_error' ) ) {
				$a['validation_error'] = wpcf7_get_validation_error( $name );
				if ( $a['validation_error'] !== '' ) {
					$a['control_class'] .= ' wpcf7-not-valid';
				}
			}

			return cf7cs_render_select( $a );
		}, $html );
	}, 5 );

	function cf7cs_extract_names( $tpl ) {
		$names = [];
		if ( ! is_string( $tpl ) || $tpl === '' ) {
			return $names;
		}

		if ( preg_match_all( '!\[custom_select\*?\s+[^\]]*?\sname\s*=\s*"([^"]+)"!i', $tpl, $mA ) ) {
			foreach ( $mA[1] as $raw ) {
				$raw = sanitize_key( $raw );
				if ( $raw !== '' ) {
					$names[] = $raw;
				}
			}
		}

		if ( preg_match_all( '!\[(?:custom_select\*?|custom_select)\s+([^\s\]"]+)!i', $tpl, $mB ) ) {
			foreach ( $mB[1] as $raw ) {
				if ( strpos( $raw, ':' ) !== false ) {
					continue;
				}
				$raw = sanitize_key( $raw );
				if ( $raw !== '' ) {
					$names[] = $raw;
				}
			}
		}
		$names = array_values( array_unique( $names ) );

		return $names;
	}

	function cf7cs_pick_cf( $a2 = null, $a3 = null ) {
		if ( is_object( $a2 ) && method_exists( $a2, 'prop' ) ) {
			return $a2;
		}
		if ( is_object( $a3 ) && method_exists( $a3, 'prop' ) ) {
			return $a3;
		}

		return null;
	}

	add_filter( 'wpcf7_collect_mail_tags', function ( $list, $a2 = null, $a3 = null ) {
		$list = (array) $list;

		$cf = cf7cs_pick_cf( $a2, $a3 );
		if ( ! $cf ) {
			return $list;
		}

		$template = (string) $cf->prop( 'form' );
		$names = [];

		if ( function_exists( 'wpcf7_scan_form_tags' ) ) {
			$scanned = wpcf7_scan_form_tags( $template );
			foreach ( (array) $scanned as $t ) {
				$type = is_object( $t ) ? ( $t->type ?? $t->basetype ?? '' ) : ( $t['type'] ?? $t['basetype'] ?? '' );
				$name = is_object( $t ) ? ( $t->name ?? '' ) : ( $t['name'] ?? '' );
				if ( strtolower( $type ) === 'custom_select' && $name ) {
					$names[] = sanitize_key( $name );
				}
			}
		}

		$names = array_merge( $names, cf7cs_extract_names( $template ) );
		$out = array_values( array_unique( array_merge( $list, $names ) ) );

		return $out;
	}, 9999, 3 );

	add_filter( 'wpcf7_mail_tag_replaced', function ( $replaced, $submitted, $is_html, $mail_tag ) {
		$name = is_object( $mail_tag ) ? ( $mail_tag->name ?? '' ) : '';
		if ( ! $name || ! isset( $_POST[ $name ] ) ) {
			return $replaced;
		}
		$val = wp_unslash( $_POST[ $name ] );

		return is_array( $val ) ? implode( ', ', array_map( 'sanitize_text_field', $val ) )
			: sanitize_text_field( (string) $val );
	}, 10, 4 );

