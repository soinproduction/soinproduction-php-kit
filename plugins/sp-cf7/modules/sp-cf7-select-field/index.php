                        var start = this.selectionStart;
                        var end = this.selectionEnd;
                        var value = this.value;
                        var lineStart = value.lastIndexOf('\n', start - 1) + 1;
                        var nextLineBreak = value.indexOf('\n', end);
                        var lineEnd = nextLineBreak === -1 ? value.length : nextLineBreak;
                        var selectedLines = value.substring(lineStart, lineEnd).split('\n');
                        var changedLines;
                        var startOffset;
                        var endOffset;

                        if (e.shiftKey) {
                            var removed = [];
                            changedLines = selectedLines.map(function(line) {
                                if (line.indexOf('\t') === 0) {
                                    removed.push(1);
                                    return line.substring(1);
                                }
                                if (line.indexOf('    ') === 0) {
                                    removed.push(4);
                                    return line.substring(4);
                                }
                                removed.push(0);
                                return line;
                            });
                            startOffset = removed[0];
                            endOffset = removed.reduce(function(total, amount) { return total + amount; }, 0);
                            this.value = value.substring(0, lineStart) + changedLines.join('\n') + value.substring(lineEnd);
                            this.selectionStart = Math.max(lineStart, start - startOffset);
                            this.selectionEnd = Math.max(this.selectionStart, end - endOffset);
                        } else {
                            changedLines = selectedLines.map(function(line) { return '\t' + line; });
                            this.value = value.substring(0, lineStart) + changedLines.join('\n') + value.substring(lineEnd);
                            this.selectionStart = start + 1;
