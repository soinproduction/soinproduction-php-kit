	function cf7cs_render_select( array $a ) {
		$a = wp_parse_args( $a, [
			'class'       => 'custom-select',
			'type'        => 'single',
			'placeholder' => '',
			'name'        => '',
			'id'          => '',
			'options'     => '',
			'active'      => '',
			'disabled'    => '',
			'required'         => false,
			'control_class'    => '',
			'validation_error' => '',
			'wpcf7_wrap'       => false,
		] );

		$opts = array_filter( array_map( 'trim', explode( '|', (string) $a['options'] ) ) );
		if ( ! $a['name'] || ! $opts ) {
			return '';
		}

		$active   = $a['active']   !== '' ? array_map( 'trim', explode( '|', (string) $a['active']   ) ) : [];
		$disabled = $a['disabled'] !== '' ? array_map( 'trim', explode( '|', (string) $a['disabled'] ) ) : [];

		$id_attr    = $a['id'] ? ' id="' . esc_attr( $a['id'] ) . '"' : '';
		$is_invalid = $a['validation_error'] !== '';

		ob_start(); ?>
		<?php if ( $a['wpcf7_wrap'] ) { ?>
			<span class="wpcf7-form-control-wrap cf7-custom-select-wrap" data-name="<?php echo esc_attr( $a['name'] ); ?>">
		<?php } ?>
		<div class="custom-select <?php echo esc_attr( trim( $a['class'] . ' ' . $a['control_class'] ) ); ?>"
			<?php echo $id_attr; ?>
			 data-type="<?php echo esc_attr( $a['type'] ); ?>"
			 data-placeholder="<?php echo esc_attr( $a['placeholder'] ); ?>"
			 data-name="<?php echo esc_attr( $a['name'] ); ?>"
			 role="combobox" aria-haspopup="listbox" aria-expanded="false"<?php echo $a['required'] ? ' aria-required="true"' : ''; ?> aria-invalid="<?php echo $is_invalid ? 'true' : 'false'; ?>"<?php echo $is_invalid && function_exists( 'wpcf7_get_validation_error_reference' ) ? ' aria-describedby="' . esc_attr( wpcf7_get_validation_error_reference( $a['name'] ) ) . '"' : ''; ?>>
			<div class="select-field custom-select-field">
				<div class="selected-options"><span class="placeholder"></span></div>
				<div class="arrow-down">
					<?php sprite(24, 24, 'chevron-down'); ?>
				</div>
			</div>
			<ul class="options-container" role="listbox">
				<?php foreach ( $opts as $v ):
					$cls = 'option'
						   . ( in_array( $v, $active,   true ) ? ' active'   : '' )
						   . ( in_array( $v, $disabled, true ) ? ' disabled' : '' ); ?>
					<li class="<?php echo esc_attr( $cls ); ?>" data-value="<?php echo esc_attr( $v ); ?>">
						<span class="option-text"><?php echo esc_html( $v ); ?></span>
					</li>
				<?php endforeach; ?>
			</ul>
		</div>
		<?php if ( $a['wpcf7_wrap'] ) { ?>
			<?php echo $a['validation_error']; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by Contact Form 7. ?>
			</span>
		<?php } ?>
		<?php
		return ob_get_clean();
	}

